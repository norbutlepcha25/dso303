#!/usr/bin/env python3
"""Audit and tidy the images used by the DSO303 Markdown pages.

  python3 utils/image_audit.py                 # report every image problem
  python3 utils/image_audit.py docs/unit5      # limit to a folder or file
  python3 utils/image_audit.py --json          # machine-readable report
  python3 utils/image_audit.py --relocate      # dry run: show planned moves
  python3 utils/image_audit.py --relocate --apply
                                               # move images into the right
                                               # folder and rewrite references

Checks, per image reference:
  missing       the file does not exist
  external      hot-linked from another site (download it and keep a copy)
  misplaced     not in the folder the convention expects (see expected_dir)
  generic-name  a name like image-1.png or "Screen Shot 2026-...png"
  no-figure     not wrapped in <figure markdown="span">
  no-caption    no <figcaption>
  no-source     no "Image Source:" line
  unknown-source  the source line says Unknown, N/A or TODO
  weak-alt      empty or placeholder alt text
  legacy-embed  old image_block / youtube_embed / iframe_embed / h5p macro:
                switch to figure() / embed() (utils/media-components.md)
  raw-iframe    a hand-written <iframe>: use embed()

The house components {{ figure(...) }} and {{ embed(...) }} (main.py) are
understood: a figure() counts as a complete figure and is checked for its
caption, source and alt text; an embed() is checked for caption and source.

Also lists images under docs/img/ that no page references (orphans), and
prints provenance hints read from each file's metadata (C2PA content
credentials, IPTC "trainedAlgorithmicMedia", generator names such as
ChatGPT/OpenAI, Gemini, Midjourney, draw.io). A hint is evidence, not proof:
no hint does not mean the image is not AI generated.

Folder convention (expected_dir):
  docs/unit<N>/topic<M>.md  ->  docs/img/U<N>/  (any subfolder of it is fine;
                                 new moves go to docs/img/U<N>/t<M>/)
  docs/Lab/*.md             ->  docs/img/labs/
  any other docs/<dir>/     ->  docs/img/<dir lower-case>/
  docs/<page>.md            ->  docs/img/site/

Line endings are preserved (several notes use CRLF).
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
IMG = DOCS / "img"
SKIP_DIRS = ("assets/icons", "teach-")
IMAGE_EXT = {".png", ".jpg", ".jpeg", ".gif", ".webp", ".svg", ".avif"}

MD_IMG = re.compile(
    r"!\[(?P<alt>[^\]]*)\]\((?P<src>[^)\s]+)(?:\s+\"[^\"]*\")?\)(?P<attrs>\{[^}]*\})?"
)
HTML_IMG = re.compile(r"<img\b[^>]*?\bsrc=[\"'](?P<src>[^\"']+)[\"'][^>]*>", re.I)
HTML_ALT = re.compile(r"\balt=[\"']([^\"']*)[\"']", re.I)
MACRO = re.compile(
    r"\{\{\s*(figure|embed|image_block|youtube_embed|iframe_embed|h5p_lumi_embed)\s*\((.*?)\)\s*\}\}", re.S
)
FIG_MACRO_SRC = re.compile(r"(\{\{\s*figure\s*\(\s*)([\"'])(.*?)\2", re.S)
FENCE = re.compile(r"^[ \t]*(```|~~~).*?^[ \t]*\1[^\n]*$", re.S | re.M)
COMMENT = re.compile(r"<!--.*?-->", re.S)
GENERIC = re.compile(
    r"^(image|img|picture|pic|photo|screenshot|screen[ _-]?shot|untitled|download|pasted|"
    r"clipboard|capture|unnamed|figure|fig|ss|scr)([ _.\-]*\d*)*$|\s",
    re.I,
)
WEAK_ALT = {"", "image", "img", "alt", "alt text", "picture", "rbs", "figure", "diagram", "screenshot"}

# byte marker -> provenance hint
MARKERS = [
    (b"trainedAlgorithmicMedia", "IPTC digital source type: AI generated"),
    (b"compositeWithTrainedAlgorithmicMedia", "IPTC: composite with AI-generated media"),
    (b"c2pa", "C2PA content credentials present"),
    (b"SynthID", "Google SynthID watermark: AI generated by a Google model (Gemini / Imagen)"),
    (b"ChatGPT", "generator: ChatGPT"),
    (b"OpenAI", "generator: OpenAI (ChatGPT / DALL-E)"),
    (b"DALL", "generator: DALL-E"),
    (b"Gemini", "generator: Google Gemini"),
    (b"Imagen", "generator: Google Imagen"),
    (b"Midjourney", "generator: Midjourney"),
    (b"Firefly", "generator: Adobe Firefly"),
    (b"Stable Diffusion", "generator: Stable Diffusion"),
    (b"Ideogram", "generator: Ideogram"),
    (b"Microsoft Designer", "generator: Microsoft Designer"),
    (b"Bing Image Creator", "generator: Bing Image Creator"),
    (b"Canva", "made with Canva"),
    (b"mxfile", "draw.io diagram"),
    (b"draw.io", "draw.io diagram"),
    (b"excalidraw", "Excalidraw diagram"),
    (b"Lucidchart", "Lucidchart diagram"),
    (b"Screenshot", "screenshot (OS metadata)"),
]


def rel(p):
    try:
        return str(Path(p).resolve().relative_to(ROOT))
    except ValueError:
        return str(p)


def expected_dir(md):
    """Folder an image used by this page should live in, and the default
    subfolder for newly moved images."""
    parts = md.relative_to(DOCS).parts
    if len(parts) == 1:
        base = IMG / "site"
        return base, base
    top = parts[0]
    m = re.fullmatch(r"unit(\d+)", top)
    if m:
        base = IMG / f"U{m.group(1)}"
        t = re.fullmatch(r"topic(\d+)\.md", parts[-1])
        return base, (base / f"t{t.group(1)}" if t else base)
    if top == "Lab":
        base = IMG / "labs"
        return base, base
    base = IMG / top.lower()
    return base, base


def resolve(md, src):
    src = src.split("#")[0].split("?")[0]
    if src.startswith("/"):
        return (DOCS / src.lstrip("/")).resolve()
    return (md.parent / src).resolve()


def provenance(path):
    try:
        data = path.read_bytes()
    except OSError:
        return []
    hints = []
    for marker, label in MARKERS:
        if marker in data and label not in hints:
            hints.append(label)
    return hints


def figure_context(lines, idx):
    """Inspect the lines around an image for the house figure template."""
    start = idx
    while start > 0 and idx - start < 3 and "<figure" not in lines[start]:
        start -= 1
    in_figure = "<figure" in lines[start]
    caption = source = False
    if in_figure:
        j = idx
        while j < len(lines) and j - idx < 6:
            if "<figcaption" in lines[j]:
                caption = True
            if "Image Source" in lines[j]:
                source = "unknown" if re.search(r"Image Source:\s*(Unknown|N/A|TODO)", lines[j], re.I) else True
            if "</figure>" in lines[j]:
                break
            j += 1
    return in_figure, caption, source


def pages(targets):
    out = []
    for t in targets:
        t = Path(t).resolve()
        files = [t] if t.is_file() else sorted(t.rglob("*.md"))
        for f in files:
            r = f.relative_to(DOCS).as_posix()
            if any(s in r for s in SKIP_DIRS):
                continue
            out.append(f)
    return out


def _blank(m):
    return re.sub(r"[^\n]", " ", m.group(0))


def parse_macro(name, args):
    """Positional and keyword arguments of a macro call, or None."""
    import ast
    try:
        call = ast.parse(f"f({args})", mode="eval").body
        pos = [ast.literal_eval(a) for a in call.args]
        kw = {k.arg: ast.literal_eval(k.value) for k in call.keywords}
    except (SyntaxError, ValueError):
        return None
    params = {
        "figure": ["src", "caption", "source", "alt", "source_url", "width"],
        "embed": ["url", "caption", "source", "source_url", "height", "intro"],
    }.get(name, [])
    out = dict(zip(params, pos))
    out.update(kw)
    return out


def scan_macros(md, text):
    """figure()/embed() calls, legacy embed macros and raw iframes."""
    masked = COMMENT.sub(_blank, FENCE.sub(_blank, text))
    refs = []
    for m in MACRO.finditer(masked):
        line = masked.count("\n", 0, m.start()) + 1
        name = m.group(1)
        if name not in ("figure", "embed"):
            refs.append(dict(page=md, line=line, src=name + "()", alt="", kind="legacy"))
            continue
        a = parse_macro(name, m.group(2)) or {}
        refs.append(dict(
            page=md, line=line, kind=name, macro=a,
            src=a.get("src") or a.get("url") or "?",
            alt=(a.get("alt") or a.get("caption") or "").strip(),
        ))
    for m in re.finditer(r"<iframe\b", masked, re.I):
        line = masked.count("\n", 0, m.start()) + 1
        refs.append(dict(page=md, line=line, src="<iframe>", alt="", kind="raw-iframe"))
    return refs


def scan(targets):
    refs = []
    for md in pages(targets):
        text = md.read_text(encoding="utf-8", errors="replace")
        refs.extend(scan_macros(md, text))
        lines = text.splitlines()
        in_fence = False
        for i, line in enumerate(lines):
            if line.lstrip().startswith(("```", "~~~")):
                in_fence = not in_fence
                continue
            if in_fence or "{{" in line:
                continue
            found = [(m.group("src"), m.group("alt")) for m in MD_IMG.finditer(line)]
            for m in HTML_IMG.finditer(line):
                a = HTML_ALT.search(m.group(0))
                found.append((m.group("src"), a.group(1) if a else ""))
            for src, alt in found:
                if "assets/icons/" in src:
                    continue
                refs.append(dict(page=md, line=i + 1, src=src, alt=alt.strip(), lines=lines, idx=i))
    return refs


def audit(refs):
    users = {}
    for r in refs:
        if r.get("kind") in ("legacy", "raw-iframe", "embed"):
            continue
        if not r["src"].startswith(("http://", "https://", "data:")):
            users.setdefault(resolve(r["page"], r["src"]), set()).add(r["page"])

    rows = []
    for r in refs:
        issues, hints = [], []
        src, md = r["src"], r["page"]
        path = None
        kind = r.get("kind", "markdown")
        if kind in ("legacy", "raw-iframe", "embed"):
            if kind == "legacy":
                issues.append("legacy-embed")
            elif kind == "raw-iframe":
                issues.append("raw-iframe")
            else:
                a = r["macro"]
                if not a.get("caption"):
                    issues.append("no-caption")
                if not a.get("source"):
                    issues.append("no-source")
                elif re.match(r"\s*(Unknown|N/A|TODO)", a["source"], re.I):
                    issues.append("unknown-source")
            rows.append(dict(page=rel(md), line=r["line"], src=src, alt=r["alt"], file=None,
                             issues=issues, provenance=[], shared=False))
            continue
        if src.startswith(("http://", "https://")):
            issues.append("external")
        elif not src.startswith("data:"):
            path = resolve(md, src)
            if not path.exists():
                issues.append("missing")
            else:
                hints = provenance(path)
                base, _ = expected_dir(md)
                if base not in path.parents:
                    issues.append("misplaced")
                if GENERIC.search(path.stem):
                    issues.append("generic-name")
        if kind == "figure":
            a = r["macro"]
            in_fig, cap = True, bool(a.get("caption"))
            srcline = a.get("source") and (
                "unknown" if re.match(r"\s*(Unknown|N/A|TODO)", a["source"], re.I) else True)
        else:
            in_fig, cap, srcline = figure_context(r["lines"], r["idx"])
        if not in_fig:
            issues.append("no-figure")
        if not cap:
            issues.append("no-caption")
        if not srcline:
            issues.append("no-source")
        elif srcline == "unknown":
            issues.append("unknown-source")
        if r["alt"].lower() in WEAK_ALT:
            issues.append("weak-alt")
        rows.append(dict(
            page=rel(md), line=r["line"], src=src, alt=r["alt"],
            file=rel(path) if path else None, issues=issues, provenance=hints,
            shared=bool(path and len(users.get(path, ())) > 1),
        ))

    # Orphans are judged against every page, not just the ones audited.
    referenced = {
        resolve(r["page"], r["src"]) for r in scan([DOCS])
        if r.get("kind") not in ("legacy", "raw-iframe", "embed")
        and not r["src"].startswith(("http://", "https://", "data:"))
    }
    orphans = sorted(
        rel(p) for p in IMG.rglob("*")
        if p.is_file() and p.suffix.lower() in IMAGE_EXT and p.resolve() not in referenced
    )
    return rows, orphans


def slug(text):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return "-".join(s.split("-")[:6]) or "figure"


def git_tracked(path):
    r = subprocess.run(["git", "ls-files", "--error-unmatch", str(path)],
                       cwd=ROOT, capture_output=True)
    return r.returncode == 0


def relocate(refs, apply):
    """Move misplaced or generically named images and rewrite references."""
    by_file = {}
    for r in refs:
        src = r["src"]
        if r.get("kind") in ("legacy", "raw-iframe", "embed"):
            continue
        if src.startswith(("http://", "https://", "data:")):
            continue
        path = resolve(r["page"], src)
        if path.exists():
            by_file.setdefault(path, []).append(r)

    moves = {}
    for path, rs in sorted(by_file.items()):
        dirs = {expected_dir(r["page"]) for r in rs}
        if len(dirs) > 1:
            print(f"skip (shared by pages in different units): {rel(path)}")
            continue
        (base, target_dir), = dirs
        misplaced = base not in path.parents
        generic = bool(GENERIC.search(path.stem))
        if not (misplaced or generic):
            continue
        name = path.name
        if generic:
            alt = next((r["alt"] for r in rs if r["alt"].lower() not in WEAK_ALT), "")
            page = rs[0]["page"]
            name = slug(alt or f"{page.parent.name}-{page.stem}-figure") + path.suffix.lower()
        dest_dir = target_dir if misplaced else path.parent
        dest = dest_dir / name
        n = 2
        while dest.exists() or dest in moves.values():
            dest = dest_dir / f"{Path(name).stem}-{n}{path.suffix.lower()}"
            n += 1
        moves[path] = dest

    if not moves:
        print("Nothing to relocate.")
        return

    for old, new in moves.items():
        print(f"{'move' if apply else 'would move'}: {rel(old)} -> {rel(new)}")
    if not apply:
        print("\nDry run. Re-run with --apply to move files and rewrite references.")
        return

    for old, new in moves.items():
        new.parent.mkdir(parents=True, exist_ok=True)
        if git_tracked(old):
            subprocess.run(["git", "mv", str(old), str(new)], cwd=ROOT, check=True)
        else:
            shutil.move(str(old), str(new))

    # Rewrite every reference on every page, preserving line endings.
    for md in pages([DOCS]):
        with open(md, encoding="utf-8", newline="") as fh:
            text = fh.read()

        def fix(src):
            if src.startswith(("http://", "https://", "data:")):
                return src
            target = moves.get(resolve(md, src))
            if not target:
                return src
            return os.path.relpath(target, md.parent).replace(os.sep, "/")

        new = MD_IMG.sub(lambda m: m.group(0).replace(
            f"]({m.group('src')}", f"]({fix(m.group('src'))}", 1), text)
        new = HTML_IMG.sub(lambda m: m.group(0).replace(
            m.group("src"), fix(m.group("src")), 1), new)
        new = FIG_MACRO_SRC.sub(lambda m: m.group(1) + m.group(2) + fix(m.group(3)) + m.group(2), new)
        if new != text:
            with open(md, "w", encoding="utf-8", newline="") as fh:
                fh.write(new)
            print(f"rewrote references in {rel(md)}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("targets", nargs="*", default=[str(DOCS)], help="Markdown files or folders (default: docs/)")
    ap.add_argument("--json", action="store_true", help="print the report as JSON")
    ap.add_argument("--relocate", action="store_true", help="plan moves into the expected folders")
    ap.add_argument("--apply", action="store_true", help="with --relocate: actually move and rewrite")
    args = ap.parse_args()

    refs = scan(args.targets)
    if args.relocate:
        relocate(refs, args.apply)
        return 0

    rows, orphans = audit(refs)
    if args.json:
        print(json.dumps(dict(images=rows, orphans=orphans), indent=2))
        return 1 if any(r["issues"] for r in rows) else 0

    bad = [r for r in rows if r["issues"]]
    current = None
    for r in bad:
        if r["page"] != current:
            current = r["page"]
            print(f"\n{current}")
        print(f"  L{r['line']}: {r['src']}")
        print(f"      issues: {', '.join(r['issues'])}{'  (shared)' if r['shared'] else ''}")
        if r["provenance"]:
            print(f"      metadata: {'; '.join(r['provenance'])}")
    print(f"\n{len(rows)} image references, {len(bad)} with issues.")
    if orphans:
        print(f"{len(orphans)} unreferenced files under docs/img/:")
        for o in orphans:
            print(f"  {o}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
